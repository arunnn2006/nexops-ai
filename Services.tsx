import { useState } from "react";
import { api } from "../api";
import { LineChart } from "../components/charts";
import { Badge, StateView, fmtTime, useAsync } from "../components/ui";
import type { Service } from "../types";

function MetricsPanel({ service }: { service: Service }) {
  const { data, loading, error, reload } = useAsync(() => api.metrics(service.id, 60), [service.id]);
  const labels = (data ?? []).map((m) => new Date(m.observed_at).toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }));
  const sampleOnly = (data ?? []).some((m) => m.source === "sample");
  return (
    <div className="panel">
      <h2>{service.name} — last {data?.length ?? 0} samples</h2>
      {sampleOnly && <p className="muted">Includes synthetic sample data generated by the demo seed.</p>}
      <StateView loading={loading} error={error} onRetry={reload} empty={!data?.length} emptyText="No metric samples ingested for this service yet.">
        <div className="grid2">
          <LineChart title="Latency (ms)" labels={labels} unit="ms" series={[{ label: "latency", color: "#4aa3ff", values: (data ?? []).map((m) => m.latency_ms) }]} />
          <LineChart title="Error rate (%)" labels={labels} unit="%" series={[{ label: "error rate", color: "#f5594e", values: (data ?? []).map((m) => m.error_rate * 100) }]} />
        </div>
      </StateView>
    </div>
  );
}

export function ServicesPage() {
  const { data, loading, error, reload } = useAsync(() => api.services(), []);
  const [selected, setSelected] = useState<Service | null>(null);
  return (
    <>
      <h1>Services</h1>
      <StateView loading={loading} error={error} onRetry={reload} empty={!data?.length} emptyText="No services registered.">
        <div className="panel tablewrap">
          <table>
            <thead><tr><th>Name</th><th>Status</th><th>Version</th><th>Environment</th><th>Recovery</th><th>Last checked</th></tr></thead>
            <tbody>
              {(data ?? []).map((s) => (
                <tr key={s.id} className="click" onClick={() => setSelected(s)} tabIndex={0}
                  onKeyDown={(e) => e.key === "Enter" && setSelected(s)} aria-label={`Show metrics for ${s.name}`}>
                  <td>{s.name}<div className="muted">{s.description}</div></td>
                  <td><Badge value={s.status} /></td><td>{s.current_version ?? "—"}</td><td>{s.environment}</td>
                  <td>{s.is_demo && s.recovery_allowed ? "simulated demo target" : "not eligible"}</td>
                  <td>{fmtTime(s.last_checked_at)}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </StateView>
      {selected ? <MetricsPanel service={selected} /> : data?.length ? <p className="muted">Select a service to see its metrics.</p> : null}
    </>
  );
}
